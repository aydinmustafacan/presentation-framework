/**
 * Helpers shared by the dev server and the production build for turning a Section into HTML.
 */
import fs from 'node:fs';
import path from 'node:path';
import { CACHE_DIR, ROOT, type Section } from './sections.ts';

export const UI_DIR = path.join(ROOT, 'framework', 'ui');

const posix = (p: string) => p.split(path.sep).join('/');

/**
 * Injected into every page (React or dropped-in HTML). It applies the light/dark theme, and
 * keeps the shell working while focus is inside the iframe: navigation keys the page did not
 * handle are forwarded upward.
 */
export const BRIDGE_SCRIPT = `<script data-presentation-bridge>(function(){
// Theme: the shell's choice (data-theme on the iframe), else the saved choice, else the OS.
var root = document.documentElement;
function applyTheme(t) {
  if (t !== 'light' && t !== 'dark') return;
  root.setAttribute('data-theme', t);
  root.style.colorScheme = t;
}
var t = null;
try { t = window.frameElement && window.frameElement.getAttribute('data-theme'); } catch (e) {}
if (!t) { try { t = localStorage.getItem('presentation.theme'); } catch (e) {} }
if (!t && window.matchMedia) t = matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
applyTheme(t);
window.addEventListener('message', function (e) {
  if (e.data && e.data.__presentation === 'theme') applyTheme(e.data.theme);
});

if (window.parent === window) return;
var KEYS = { ArrowRight:1, ArrowLeft:1, PageDown:1, PageUp:1, Home:1, End:1, f:1, s:1, t:1 };
window.addEventListener('keydown', function (e) {
  // Chords: Ctrl+A / Ctrl+Shift+A move between sections, Cmd/Ctrl+1 toggles the sidebar.
  // Ctrl+A is left alone in text fields (select all / line start).
  var chord = null, el = e.target;
  var editing = el && (el.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(el.tagName));
  if (e.code === 'KeyA' && e.ctrlKey && !e.metaKey && !e.altKey && !editing) chord = e.shiftKey ? 'ArrowLeft' : 'ArrowRight';
  else if (e.code === 'Digit1' && (e.metaKey || e.ctrlKey) && !e.shiftKey && !e.altKey) chord = 's';
  if (chord) {
    e.preventDefault();
    window.parent.postMessage({ __presentation: 'key', key: chord }, '*');
    return;
  }
  if (e.defaultPrevented || e.altKey || e.ctrlKey || e.metaKey || !KEYS[e.key]) return;
  var t = e.target;
  if (t && (t.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName))) return;
  if (e.key === 'Home' || e.key === 'End' || e.key === 'PageUp' || e.key === 'PageDown') {
    var se = document.scrollingElement;
    if (se && se.scrollHeight > se.clientHeight + 4) return; // let a long page scroll
  }
  e.preventDefault();
  window.parent.postMessage({ __presentation: 'key', key: e.key }, '*');
});
})();</script>`;

export function injectBridge(html: string): string {
  if (html.includes('data-presentation-bridge')) return html;
  const i = html.search(/<\/body>/i);
  return i === -1 ? html + BRIDGE_SCRIPT : html.slice(0, i) + BRIDGE_SCRIPT + html.slice(i);
}

/** Absolute directory holding the generated entry for a React section. */
export function entryDir(s: Section) {
  return path.join(CACHE_DIR, s.id);
}

/**
 * Writes `.presentation/<id>/entry.tsx` + `index.html`. The entry mounts the section's default
 * export inside the framework's SectionProvider so <Slide> can show the number and title.
 */
export function writeReactEntry(s: Section) {
  const dir = entryDir(s);
  fs.mkdirSync(dir, { recursive: true });
  const info = JSON.stringify({ number: s.number, title: s.title, id: s.id });
  const entry = `// generated by framework/pages.ts — do not edit
import { StrictMode, createElement } from 'react';
import { createRoot } from 'react-dom/client';
import { SectionProvider } from '${posix(path.join(UI_DIR, 'index.tsx'))}';
import '${posix(path.join(UI_DIR, 'page.css'))}';
import Page from '${posix(s.source)}';

createRoot(document.getElementById('root')!).render(
  createElement(StrictMode, null, createElement(SectionProvider, { value: ${info} }, createElement(Page))),
);
`;
  writeIfChanged(path.join(dir, 'entry.tsx'), entry);
  writeIfChanged(path.join(dir, 'index.html'), pageHtml(s, './entry.tsx'));
}

export function pageHtml(s: Section, entrySrc: string) {
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${s.number} ${escapeHtml(s.title)}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="${entrySrc}"></script>
  </body>
</html>
`;
}

function writeIfChanged(file: string, content: string) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  fs.writeFileSync(file, content);
}

export function escapeHtml(s: string) {
  return s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
}

/** Serialize data for a <script> tag without letting "</script>" or "<!--" break out of it. */
export function safeJson(data: unknown) {
  // escape '<' and the two JS line terminators U+2028/U+2029 that are legal in JSON strings
  return JSON.stringify(data).replace(/[<\u2028\u2029]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
}

export const posixPath = posix;
