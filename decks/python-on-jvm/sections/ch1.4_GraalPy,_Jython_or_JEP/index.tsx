import { useState, type CSSProperties } from 'react';
import { Callout, Grid, Slide } from '@framework';
import { A, RT, RT_IDS, jythonJarBytes, type RtId } from '../../../graalpy/sections/_shared/alt.ts';
import { MB } from '../../../graalpy/sections/_shared/data.ts';
import { jepDocs } from '../_shared/demo.ts';
import { SourceLinks } from '../_shared/ui.tsx';
import './style.css';

type Kind = 'java' | 'py' | 'native' | 'jit';
interface Layer { name: string; sub: string; kind: Kind; text: string }

const STACKS: Record<RtId, Layer[]> = {
  jython: [
    { name: 'Your Java app', sub: 'PythonInterpreter', kind: 'java', text: 'Put Jython on the classpath and use `PythonInterpreter` to run Python and retrieve values.' },
    { name: 'Jython compiler', sub: '.py → JVM bytecode', kind: 'py', text: 'Jython compiles Python modules to JVM classes at load time. Python values are represented by Java objects.' },
    { name: 'HotSpot JIT', sub: 'C1 / C2 on HotSpot', kind: 'jit', text: 'HotSpot can optimize frequently executed Jython-generated bytecode using the same JIT compiler it uses for Java code.' },
    { name: 'JVM only', sub: 'No CPython runtime or GIL', kind: 'java', text: `The benchmark used a ${MB(jythonJarBytes, 0)} standalone JAR with Python ${A.runtimes.jython.python}. Jython has no global interpreter lock (GIL). CPython C extensions require a different runtime.` },
  ],
  jep: [
    { name: 'Your Java app', sub: 'SharedInterpreter / SubInterpreter', kind: 'java', text: 'JEP exposes `exec()`, `invoke()` and `getValue()`. Interpreter operations run on the Java thread that created the interpreter.' },
    { name: 'JNI bridge', sub: 'libjep (C)', kind: 'native', text: 'The native JEP library uses the Java Native Interface (JNI) to call CPython and convert values between the two runtimes.' },
    { name: 'CPython', sub: `libpython ${A.runtimes.jep.python}`, kind: 'py', text: 'The native CPython interpreter runs inside the JVM process. Python execution and GIL behavior depend on the CPython build and interpreter configuration.' },
    { name: 'C extensions', sub: 'NumPy, pandas …', kind: 'native', text: 'The repo benchmark imported NumPy and ran a calculation with a shared interpreter. Verify extension support for the interpreter mode you use and provision CPython, libjep and the packages on the deployment target.' },
  ],
  graalpy: [
    { name: 'Your Java app', sub: 'Context / Value', kind: 'java', text: 'Java creates a Polyglot `Context` and invokes Python functions through `Value`. The Flask example bundles the runtime and packages in the application JAR.' },
    { name: 'GraalPy', sub: 'Python runtime on Truffle', kind: 'py', text: `The benchmark used GraalPy’s Python ${A.runtimes.graalpy.python} implementation. Truffle specializes Python operations at runtime, and GraalPy provides a compatibility layer for supported native extensions.` },
    { name: 'Graal JIT', sub: 'Supported host and compiler', kind: 'jit', text: 'On a supported host with runtime compilation enabled, the Graal compiler can optimize hot Python code to machine code. The demo on local Corretto 25 used the fallback interpreter.' },
    { name: 'JVM + bundled natives', sub: 'Runtime resources in the JAR', kind: 'native', text: 'The demo JAR bundles GraalPy runtime resources. The runtime may extract resources to disk. Check the target OS and architecture and verify each native extension against GraalPy.' },
  ],
};

const KIND_LABEL: Record<Kind, string> = {
  java: 'Java / JVM',
  py: 'Where Python runs',
  native: 'Native code',
  jit: 'JIT compiler',
};

export default function RuntimeComparison() {
  const [[runtime, index], setSelection] = useState<[RtId, number]>(['jep', 2]);
  const layer = STACKS[runtime][index];
  const tone = layer.kind === 'java' ? 'blue' : layer.kind === 'jit' ? 'green' : layer.kind === 'py' ? 'accent' : 'muted';

  return (
    <Slide
      title={<>GraalPy, <span className="t-jython">Jython</span> or <span className="t-jep">JEP</span>?</>}
      lead="Select a layer to see where Python runs in each stack and what that means for the Flask service."
    >
      <Grid cols={3} gap={16}>
        {RT_IDS.map((id) => (
          <section key={id} className="stack" aria-label={RT[id].name} style={{ '--rt': `var(--${RT[id].tone})` } as CSSProperties}>
            <div className="stack-head">
              <b>{RT[id].name}</b>
              <span className="muted small">{RT[id].how}</span>
            </div>
            {STACKS[id].map((item, i) => (
              <button
                key={item.name}
                type="button"
                className={`slayer k-${item.kind}`}
                aria-pressed={runtime === id && index === i}
                onMouseEnter={() => setSelection([id, i])}
                onClick={() => setSelection([id, i])}
              >
                <b>{item.name}</b>
                <span>{item.sub}</span>
              </button>
            ))}
            <div className="stack-foot mono small">{RT[id].version}</div>
          </section>
        ))}
      </Grid>
      <div aria-live="polite">
        <Callout tone={tone} title={`${RT[runtime].name} · ${layer.name}`}>
          <span className="muted small">{KIND_LABEL[layer.kind]}. </span>
          {layer.text.split('`').map((text, i) => i % 2 ? <code key={i}>{text}</code> : text)}
        </Callout>
      </div>
      <div className="legend small muted">
        {(Object.keys(KIND_LABEL) as Kind[]).map((kind) => (
          <span key={kind} className={`lg k-${kind}`}>{KIND_LABEL[kind]}</span>
        ))}
      </div>
      <p className="small-note">The versions shown come from the GraalPy deck’s benchmark on {A.machine} using {A.versions.jdk}.</p>
      <SourceLinks links={[
        ['Jython bytecode compilation', 'https://www.jython.org/jyspecific.html'],
        ['How JEP works', jepDocs],
        ['GraalVM runtime optimization', 'https://www.graalvm.org/jdk25.5/reference-manual/embed-languages/#runtime-optimization-support'],
      ]} />
    </Slide>
  );
}
